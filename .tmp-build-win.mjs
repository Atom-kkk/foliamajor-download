import { readFileSync } from 'node:fs';
import { build, Platform, Arch } from 'electron-builder';
const ROOT = '/Users/lyh/Downloads/folia-major';
const pkg = JSON.parse(readFileSync(`${ROOT}/package.json`, 'utf8'));
const config = structuredClone(pkg.build);
config.beforePack = '/tmp/win-beforePack.cjs';
config.afterPack = '/tmp/win-afterPack.cjs';
config.electronDist = '/tmp/ewin';
config.publish = null;
config.win.extraResources = [];
config.win.target = ['dir'];
config.win.icon = 'build/icon.ico';
await build({ targets: Platform.WINDOWS.createTarget(['dir'], Arch.x64), config, publish: 'never' });
console.log('[build-win] done');
